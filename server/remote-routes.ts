const API = /^\/(api|auth)\//;

// The first matched handler is the one that answers (Hono runs them in order); middleware is
// "ALL" and the SPA's "/*" is not an API route. No API route matched: the 404 answers.
export const remoteAllowlist =
  (routes: Record<string, Reach> = ROUTES): MiddlewareHandler =>
  async (c, next) => {
    if (!isRemoteRequest(c.req.raw)) return next();
    const route = matchedRoutes(c).find((r) => r.method !== "ALL" && API.test(r.path));
    if (!route) return next();
    const reach = routes[`${route.method} ${route.path}`];
    if (reach === "remote") return next();
    if (reach === "desktop")
      return c.json(
        {
          error: "local_desktop_required",
          detail: "Esta acción se realiza en el ordenador anfitrión.",
        },
        409,
      );
    return c.json({ error: "remote_not_allowed" }, 403);
  };
