export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 16 }: { name: IconName; size?: number }) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      size={size}
      strokeWidth={1.75}
      fill={name === "stop" || name === "play" ? "currentColor" : "none"}
      aria-hidden
      focusable="false"
    />
  );
}
